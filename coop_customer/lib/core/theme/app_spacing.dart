/// Spacing, radius and elevation tokens from the Heritage Modern design system.
abstract final class AppSpacing {
  static const unit = 4.0;
  static const stackSm = 8.0;
  static const stackMd = 16.0;
  static const stackLg = 32.0;
  static const marginMobile = 16.0;
  static const gutter = 24.0;
}

abstract final class AppRadius {
  static const sm = 4.0; // rounded (0.25rem)
  static const md = 8.0; // input fields, small components
  static const lg = 12.0; // standard cards and large buttons
  static const xl = 24.0; // chips and badges
  static const full = 9999.0;
}
